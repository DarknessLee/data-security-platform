const TAG_POOL = ['个人信息', '重要数据', '核心数据', '对外共享', '跨境', '高敏感', '实时流', '离线批处理', '含身份证号', '含手机号', '含生物特征', '涉密', '需脱敏', '审计留痕'];

export async function seedAssets(conn, ref) {
  const rng = createRng(20261107);
  const catIdByCode = {};
  for (const c of CATEGORIES) {
    const [r] = await conn.query('INSERT INTO asset_category (category_code, category_name, parent_id, description, sort) VALUES (?,?,?,?,?)', [c.code, c.name, 0, c.desc, c.sort]);
    catIdByCode[c.code] = r.insertId;
  }

  const assets = [];
  let seq = 0;
  for (const row of ASSETS) {
    const [name, cat, deptCode, system, type, level, format, sizeGb, rowCount, owner, status, sensitivity, quality] = row;
    seq += 1;
    const assetCode = `DA-2026-${String(seq).padStart(4, '0')}`;
    const discovered = daysAgo(randInt(rng, 30, 400), randInt(rng, 8, 20), randInt(rng, 0, 59));
    const lastAccess = daysAgo(randInt(rng, 0, 20), randInt(rng, 8, 22), randInt(rng, 0, 59));
    const stage = status === '已归档' ? '销毁' : pick(rng, ['存储', '使用', '使用', '共享', '采集']);
    const [r] = await conn.query(
      `INSERT INTO data_asset (asset_code, asset_name, category_id, dept_id, source_system, data_type, data_level, file_format, size_gb, row_count, owner, status, lifecycle_stage, sensitivity_score, quality_score, description, discovered_at, last_access_at, created_at, updated_at)
       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
      [assetCode, name, catIdByCode[cat], ref.deptIdByCode[deptCode], system, type, level, format, sizeGb, rowCount, owner, status, stage, sensitivity, quality,
        `${name}，来源于${system}，用于数据共享、业务分析与安全审计等场景，按${level}级数据管理要求实施分级保护。`,
        fmtDateTime(discovered), fmtDateTime(lastAccess), fmtDateTime(discovered), fmtDateTime(lastAccess)],
    );
    const assetId = r.insertId;
    assets.push({ id: assetId, name, cat, deptCode, level, type, owner, status });

    const tags = pickMany(rng, TAG_POOL, randInt(rng, 1, 4));
    for (const t of tags) await conn.query('INSERT INTO asset_tag (asset_id, tag_name) VALUES (?,?)', [assetId, t]);

    const stages = ['采集', '存储', '使用', '共享'];
    if (stage === '销毁') stages.push('销毁');
    for (let i = 0; i < stages.length; i += 1) {
      const st = stages[i];
      const at = daysAgo(randInt(rng, 5, 300), randInt(rng, 8, 20), randInt(rng, 0, 59));
      const actions = {
        采集: `通过${system}自动采集并登记元数据`,
        存储: `落库${format}，完成加密存储与访问授权`,
        使用: '业务部门按授权范围查询使用，操作留痕',
        共享: '通过数据共享交换平台对外提供，已完成合规审批',
        销毁: '达到留存期限，按数据销毁规程完成销毁并留档',
      };
      await conn.query('INSERT INTO asset_lifecycle (asset_id, stage, action, operator, detail, occurred_at) VALUES (?,?,?,?,?,?)', [
        assetId, st, actions[st], owner, `${name} · ${st}环节记录`, fmtDateTime(at),
      ]);
    }
  }

  return { catIdByCode, assets };
}
